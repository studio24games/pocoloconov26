// Writes math/strips.generated.js from reelopt53 results. Usage: node gen_strips53.mjs <base.json|keep> <double.json|keep>
import fs from 'node:fs';
import { STRIPS } from '../../math/strips.generated.js';
const [b, d] = process.argv.slice(2);
const pick = (f, set) => (f === 'keep' ? STRIPS[set] : JSON.parse(fs.readFileSync(f, 'utf8')).strips);
const fmt = arr => arr.map(s => '    ' + JSON.stringify(s)).join(',\n');
fs.writeFileSync(new URL('../../math/strips.generated.js', import.meta.url), `// GENERATED by tools/math/reelopt53.mjs + gen_strips53.mjs (v0.53, 27 Oct) - do not hand-edit.
// Coin and Wild positions are unchanged, so coins on screen, triggers, near misses and the meter are exactly as before.
// v0.53 (client item 11): line wins under 0.5x about half as often (about 1 spin in 17 instead of 1 in 10), 0.5-1x
// wins kept, the RTP saved moved into 2-5x wins and a more frequent Loco Spin (1 in 94).
export const STRIPS = {
  base: [
${fmt(pick(b, 'base'))},
  ],
  double: [
${fmt(pick(d, 'double'))},
  ],
};
`);
console.log('written');
