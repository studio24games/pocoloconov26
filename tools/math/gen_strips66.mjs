// v0.66: writes math/strips.generated.js from reelopt63 results (the two versions, base + Double Chance).
// Usage: node tools/math/gen_strips66.mjs <base.json|keep> <double.json|keep> <baseLean.json|keep> <doubleLean.json|keep>
import fs from 'node:fs';
import { STRIPS } from '../../math/strips.generated.js';
const names = ['base', 'double', 'baseLean', 'doubleLean'];
const args = process.argv.slice(2);
const pick = (f, set) => (f === 'keep' || !f ? (STRIPS[set] ?? STRIPS[set.replace('Lean', '')]) : JSON.parse(fs.readFileSync(f, 'utf8')).strips);
const fmt = arr => arr.map(s => '    ' + JSON.stringify(s)).join(',\n');
fs.writeFileSync(new URL('../../math/strips.generated.js', import.meta.url), `// GENERATED by tools/math/reelopt63.mjs + gen_strips66.mjs (v0.66 / math 0.9.0, 30 Oct) - do not hand-edit.
// Two versions, each with base and Double Chance reels:
//   base / double            the Golden Dragon version: line wins on about 1 spin in 4, mostly under the stake
//   baseLean / doubleLean    the Experiment (PROFILES.lean): wins below the stake on about 13% of spins, more 1-2x wins
// Curtains (Q): one symbol on the middle reel; a curtain anywhere on a reel draws across the whole reel
// (MYSTERY.expandReel), so curtains always come as full-reel blocks, on about 1 spin in 15.
export const STRIPS = {
${names.map((n, i) => `  ${n}: [\n${fmt(pick(args[i], n))},\n  ],`).join('\n')}
};
`);
console.log('written');
